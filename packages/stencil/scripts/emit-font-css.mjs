import { readFileSync, writeFileSync, existsSync } from 'node:fs';

// The @font-face source of truth. It is deliberately not imported by dda-bundle.css: Stencil
// compiles that file into BOTH dist/dda/dda.css and a globalStyles string, and prepends that
// string as a <style> into every shadow:true component's shadow root, where @font-face is
// ignored and the bytes are wasted. Font delivery is a stylesheet concern, so the rules are
// attached to the published stylesheet here instead and exist in exactly one place.
const FONT_CSS_PATH = 'src/global/fonts.css';

// The published stylesheet. Its own directory is what the ../assets/fonts/dubai/ URLs
// resolve against, which is why the rules are correct here and nowhere else.
const CSS_PATH = 'dist/dda/dda.css';

// The dev-server copy. Built only by the `www` output target, so it is optional: a build that
// did not produce it is not a fault, and it is skipped silently.
const WWW_CSS_PATH = 'www/build/dda.css';

// Marks the appended region. Its presence is the idempotency test, so it must be stable.
const BANNER = `/* Generated by scripts/emit-font-css.mjs from ${FONT_CSS_PATH} — do not edit here. */`;

/**
 * Append the font layer to a stylesheet, separated by a generated banner naming the source.
 *
 * Appending (rather than prepending) is correct CSS: only `@import` is required to come first,
 * and `@font-face` may follow any rule. Prepending would push the bundle's own `@import`s down
 * and invalidate them.
 *
 * Idempotent by design — the emit step runs on every build, and a build may append to a
 * stylesheet that a previous run already extended. When the banner is already present the input
 * is returned unchanged.
 * @param {string} cssText the published stylesheet's current text
 * @param {string} fontCssText the contents of src/global/fonts.css
 * @returns {string} the combined stylesheet text
 */
export function appendFontLayer(cssText, fontCssText) {
  if (cssText.includes(BANNER)) return cssText;

  const fonts = fontCssText.trim();
  if (fonts === '') return cssText;

  const head = cssText.endsWith('\n') ? cssText : `${cssText}\n`;
  return `${head}\n${BANNER}\n${fonts}\n`;
}

/**
 * The banner this module writes. Exported so callers and tests can assert on it without
 * duplicating the string.
 * @returns {string}
 */
export function fontLayerBanner() {
  return BANNER;
}

function readOrFail(path, hint) {
  try {
    return readFileSync(path, 'utf8');
  } catch (err) {
    if (err.code === 'ENOENT') {
      console.error(`${path} not found: ${hint}`);
      process.exit(1);
    }
    throw err;
  }
}

// Run as a command, not as an import.
if (process.argv[1] && process.argv[1].endsWith('emit-font-css.mjs')) {
  const fontCssText = readOrFail(FONT_CSS_PATH, 'the font layer is the source of truth for @font-face and must exist');
  const cssText = readOrFail(CSS_PATH, 'run "npx stencil build" first');

  const targets = [CSS_PATH, ...(existsSync(WWW_CSS_PATH) ? [WWW_CSS_PATH] : [])];
  const written = [];

  for (const target of targets) {
    const current = target === CSS_PATH ? cssText : readFileSync(target, 'utf8');
    const next = appendFontLayer(current, fontCssText);
    if (next === current) continue;
    writeFileSync(target, next);
    written.push(target);
  }

  console.log(
    written.length === 0
      ? `OK: font layer already present in ${targets.join(', ')}`
      : `OK: appended ${FONT_CSS_PATH} to ${written.join(', ')}`,
  );
}
